import test from 'node:test';
import assert from 'node:assert/strict';
import {randomUUID} from 'node:crypto';
import {pool} from '../lib/db';
import {perform} from '../lib/workflow';
import type {Actor} from '../lib/auth';

test('demo application passes role, signature, transfer, repayment, and ledger controls',async()=>{
  const users=await pool.query<Actor>('SELECT id,name,email,role,branch_id,customer_id FROM users WHERE email IN ($1,$2,$3)',
    ['owner@local.test','officer@local.test','customer@local.test']);
  const owner=users.rows.find(u=>u.role==='owner')!,officer=users.rows.find(u=>u.role==='officer')!,customer=users.rows.find(u=>u.role==='customer')!;
  assert.ok(owner&&officer&&customer,'demo users seeded');
  const created=await perform(officer,{type:'create',customerId:customer.customer_id!,principal:500000,weeks:4});
  const id=created.id;
  await assert.rejects(perform(officer,{type:'approve',applicationId:id}),/Forbidden/);
  const approved=await perform(owner,{type:'approve',applicationId:id});
  assert.ok(approved.hash);
  assert.equal(approved.hash.length,64);
  await assert.rejects(perform(owner,{type:'authorize',applicationId:id}),/Signed agreement required/);
  await assert.rejects(perform(officer,{type:'sign',applicationId:id}),/Forbidden/);
  await perform(customer,{type:'sign',applicationId:id});
  await perform(owner,{type:'authorize',applicationId:id});
  const key=randomUUID();
  await perform(owner,{type:'initiate',applicationId:id,idempotencyKey:key});
  const replay=await perform(owner,{type:'initiate',applicationId:id,idempotencyKey:key});
  assert.equal(replay.replayed,true);
  await assert.rejects(perform(officer,{type:'confirm',applicationId:id,bankReference:'000123',proof:'demo settlement'}),/Forbidden/);
  await perform(owner,{type:'confirm',applicationId:id,bankReference:`000${Date.now()}${Math.floor(Math.random()*1000)}`,proof:'Demo bank settlement evidence'});
  const paymentRef=`PAY-${randomUUID()}`;
  await perform(owner,{type:'payment',applicationId:id,bankReference:paymentRef,amount:100000});
  await assert.rejects(perform(owner,{type:'payment',applicationId:id,bankReference:paymentRef,amount:100000}),/duplicate key/);
  await perform(owner,{type:'payment',applicationId:id,bankReference:randomUUID(),amount:410000});
  await perform(owner,{type:'close',applicationId:id});
  const result=await pool.query('SELECT status FROM applications WHERE id=$1',[id]);
  assert.equal(result.rows[0].status,'closed');
  const balance=await pool.query(`SELECT j.id,SUM(l.debit-l.credit)::bigint AS difference FROM journals j JOIN journal_lines l ON l.journal_id=j.id WHERE j.application_id=$1 GROUP BY j.id`,[id]);
  assert.ok(balance.rows.length>=3);
  assert.ok(balance.rows.every(r=>Number(r.difference)===0));
  const ledger=await pool.query(`SELECT l.account,SUM(l.debit-l.credit)::bigint AS balance FROM journals j JOIN journal_lines l ON l.journal_id=j.id WHERE j.application_id=$1 AND l.account IN ('principal_receivable','interest_receivable') GROUP BY l.account`,[id]);
  assert.ok(ledger.rows.every(r=>Number(r.balance)===0));
  await assert.rejects(perform(officer,{type:'policy',minPrincipal:100000,maxPrincipal:5000000,flatInterestBps:200,minWeeks:1,maxWeeks:52}),/Forbidden/);
  const version=await perform(owner,{type:'policy',minPrincipal:100000,maxPrincipal:5000000,flatInterestBps:200,minWeeks:1,maxWeeks:52});
  assert.ok(version.version);
  assert.ok(version.version>=2);
  const nik=`${Date.now().toString().slice(-13)}${Math.floor(Math.random()*1000).toString().padStart(3,'0')}`;
  await assert.rejects(perform(owner,{type:'customer',name:'Test Borrower',nik,phone:'081234567890',bankName:'Demo Bank',accountNumber:'0012345678'}),/Forbidden/);
  const newCustomer=await perform(officer,{type:'customer',name:'Test Borrower',nik,phone:'081234567890',bankName:'Demo Bank',accountNumber:'0012345678'});
  await assert.rejects(perform(officer,{type:'customer',name:'Duplicate',nik,phone:'081234567890',bankName:'Demo Bank',accountNumber:'0012345678'}),/duplicate key/);
  assert.ok(newCustomer.id);
});
